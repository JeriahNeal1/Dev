"""Offline exact OEM parser replay: one/two declarations then first owned block.

Imports the retained instruction interpreter; never calls retained main routines
or physical transport. All new output stays beside this script.
"""
import sys
sys.dont_write_bytecode = True
import json, gzip, hashlib
from pathlib import Path

OUT = Path(__file__).resolve().parent
CONTRACTS = Path(r'C:\Dev\A2WC511R_ReadKernel\evidence\contracts')
sys.path.insert(0, str(CONTRACTS))
from verify_upload_wire_rk02 import Memory, CPU, sh, common, KERNEL

STOCK = common.STOCK
CURRENT = OUT.parent/'current.preserved.bin'
STOCK_SHA = '22d52a5b3de7d86562eed2f85cca772db10e0949fcedc2d61b7540b45f760218'
CURRENT_SHA = 'bf10be6d7c75b4f2ae663b0d57a912e6e9ef7654ccfc985195954596e50427b2'
KERNEL_SHA = '3a65d6f0700bae394a24ba9f552d03500b7f66e6344ec57613f10bfd360d8581'

def pin(path):
    path = Path(path)
    return {'path': str(path), 'bytes': path.stat().st_size,
            'sha256': hashlib.sha256(path.read_bytes()).hexdigest()}

def require(value, detail):
    if not value:
        raise RuntimeError(detail)

def main():
    prior_path = CONTRACTS/'UPLOAD_WIRE_CONTRACT_RK02.json'
    prior = json.loads(prior_path.read_text())
    for item in prior['inputs']:
        require(pin(item['path'])['sha256'] == item['sha256'], 'Retained input changed: '+item['path'])
    kernel = KERNEL.read_bytes()
    require(hashlib.sha256(kernel).hexdigest() == KERNEL_SHA, 'Kernel changed')
    # These requests are frozen retained instruction-execution inputs, not
    # generated by the new native host or a new fake-provider model.
    declaration = bytes.fromhex(prior['frames'][0]['request'])
    first = bytes.fromhex(prior['frames'][1]['request'])
    require(len(first) == 137 and first[3] == 132, 'First block frame size')
    rows = []
    for label, path, digest in [('stock', STOCK, STOCK_SHA), ('current', CURRENT, CURRENT_SHA)]:
        rom = sh.ROM.load(path, digest)
        for declarations in [1, 2]:
            mem = Memory(rom)
            mem.initialize(0xFFFFBB80, bytes(0x480))
            mem.initialize(0xFFFFBFBA, b'\x01')
            mem.initialize(0xFFFFBFC8, b'\x01')
            mem.write_allowlist = [(0xFFFFBB80, 0xFFFFC000), (0xFFFF3000, 0xFFFF3080)]
            instructions, transactions, declaration_states = [], [], []
            for index, frame in enumerate([declaration]*declarations + [first]):
                tx_start = len(mem.tx)
                steps_before = len(instructions)
                events_before = len(mem.events)
                for byte in frame:
                    mem.byte = byte
                    cpu = CPU(mem, [(0x13F6, 0x1F40)], (0xFFFFBB80, 0xFFFFBFA0))
                    cpu.pc, cpu.pr, cpu.r[15] = 0x1440, 0xFFFFFFFC, 0xFFFFBFA0
                    cpu.call_context = ['00001440']
                    cpu.track_control_sources = False
                    cpu._set_system('sr', 0xF0, {'explicit_loader_entry_fixture'})
                    for _ in range(15000):
                        cpu.step()
                        require(cpu.pc != 0xFFFF3004, 'Unexpected kernel entry')
                        if cpu.returned:
                            require(cpu.pc == 0xFFFFFFFC and cpu.r[15] == 0xFFFFBFA0 and not cpu.pending, 'Parser return ABI')
                            break
                    else:
                        raise RuntimeError('Parser instruction limit')
                    instructions.extend(cpu.trace)
                reply = bytes(mem.tx[tx_start:])
                expected = bytes.fromhex('80f0100274847a' if index < declarations else '80f0100176f7')
                require(reply == expected, 'OEM reply mismatch: '+reply.hex())
                writes = [x for x in mem.events[events_before:] if x['mode'] == 'w' and 0xFFFF3000 <= int(x['address'], 16) < 0xFFFF3080]
                require(len(writes) == (0 if index < declarations else 32), 'Unexpected RAM upload store count')
                state = bytes(mem.ram[0xBFA0:0xBFD0]).hex()
                transactions.append({'index': index, 'request': frame.hex(), 'reply_from_executed_TDR': reply.hex(),
                                     'instructions': len(instructions)-steps_before,
                                     'upload_stores': len(writes), 'loader_state_BFA0_BFD0': state})
                if index < declarations:
                    declaration_states.append(state)
            stores = [x for x in mem.events if x['mode'] == 'w' and 0xFFFF3000 <= int(x['address'], 16) < 0xFFFF3080]
            actual = bytes(mem.ram[0x3000:0x3080])
            require(actual == kernel[:128], 'Plaintext differs from owned kernel')
            require([int(x['address'], 16) for x in stores] == list(range(0xFFFF3000, 0xFFFF3080, 4)), 'Store address sequence')
            require(all(x['pc'] == '00001646' and x['size'] == 4 for x in stores), 'Store operation changed')
            require(not any(0xFFFFE800 <= int(x['address'], 16) < 0xFFFFE807 for x in mem.mmio), 'Flash controller access')
            trace = {'instructions': instructions, 'memory': mem.events, 'mmio': mem.mmio}
            packed = gzip.compress(json.dumps(trace, sort_keys=True, separators=(',', ':')).encode(), mtime=0)
            trace_path = OUT/f'{label}_{declarations}_declarations.trace.json.gz'
            trace_path.write_bytes(packed)
            rows.append({'case': f'{label}_{declarations}_declarations', 'ROM': pin(path),
                         'declaration_count': declarations, 'transactions': transactions,
                         'declaration_state_identical': len(set(declaration_states)) == 1,
                         'first128_plaintext_hex': actual.hex(), 'first128_plaintext_sha256': hashlib.sha256(actual).hexdigest(),
                         'stores': stores, 'instructions': len(instructions),
                         'executed_pc_count': len({x['pc'] for x in instructions}),
                         'trace': pin(trace_path), 'kernel_entered': False, 'flash_controller_accesses': 0})
    require(len({x['first128_plaintext_sha256'] for x in rows}) == 1, 'Cross-case plaintext mismatch')
    report = {'schema': 1, 'status': 'PASS_EXACT_OEM_SINGLE_DUPLICATE34_FIRST36_REPLAY',
              'inputs': [pin(__file__), pin(prior_path), pin(KERNEL), pin(CONTRACTS/'verify_upload_wire_rk02.py'),
                         pin(CONTRACTS/'verify_boot_entry.py'), pin(CONTRACTS/'verify_kwp_contract.py'),
                         pin(CONTRACTS/'verify_oem_contracts.py'), pin(common.SIM)],
              'cases': rows, 'physical_operations': 0,
              'conclusion': 'One accepted34 is sufficient for the first owned128-byte36 block in both exact ROMs. An immediate identical second34 is accepted and preserves the recorded loader declaration state.',
              'assumptions': ['Explicit admitted loader state BFBA=1 and BFC8=1; initialized parser/stack RAM.',
                              'Actual RDR parser instructions execute with supplied ready/TEND84 and nonexpired watchdog register values.',
                              'No electrical UART waveform, hardware time, asynchronous interrupt/DMA/NMI or reset is modeled.'],
              'limits': ['A duplicate before the first block is not a retry authorization after an error or after RAM data transmission.',
                         'Only the first128-byte block is executed here; no kernel start, ROM read or flash operation.',
                         'Current-image code equivalence does not independently prove physical clock, programming admission or line timing.']}
    require(all(x['declaration_state_identical'] for x in rows), 'Duplicate34 changes recorded declaration state')
    (OUT/'FIRST_BLOCK_REPLAY.json').write_text(json.dumps(report, indent=2)+'\n')
    print(json.dumps({'status': report['status'], 'cases': len(rows), 'instructions': sum(x['instructions'] for x in rows),
                      'first128_sha256': rows[0]['first128_plaintext_sha256'], 'report': pin(OUT/'FIRST_BLOCK_REPLAY.json')}))

if __name__ == '__main__':
    main()
