"""Remove audit-only allocations from the frozen step; preserve ISA statements."""
import ast
from hashlib import sha256
import inspect
from pathlib import Path
import textwrap
from .core import sh2e,CORE_SHA256

class AuditOnly(ast.NodeTransformer):
    def __init__(self):self.changed=[]
    def visit_Assign(self,node):
        targets={n.id for t in node.targets for n in ast.walk(t) if isinstance(n,ast.Name)}
        attributes=[ast.unparse(t) for t in node.targets if isinstance(t,ast.Attribute)]
        if targets&{'before','before_pr','before_t','before_system'}:
            self.changed.append('remove verbose before-state snapshot');return None
        if attributes and attributes[0] in ('self.memory.call_context','self.memory.control_sources'):
            self.changed.append('remove provenance-only memory context');return None
        if targets=={'const'}:
            self.changed.append('empty instruction provenance');node.value=ast.Call(func=ast.Name(id='set',ctx=ast.Load()),args=[],keywords=[])
        if targets=={'spec'}:
            self.changed.append('cache immutable opcode metadata');node.value=ast.parse('self._decode_cache.get(op)',mode='eval').body
        return self.generic_visit(node)
    def visit_Expr(self,node):
        if isinstance(node.value,ast.Call) and ast.unparse(node.value.func)=='self.trace.append':
            self.changed.append('replace verbose trace object with exact step count')
            return ast.parse('self.trace.count += 1').body[0]
        return self.generic_visit(node)

def run():
    original=textwrap.dedent(inspect.getsource(sh2e.CPU.step))
    tree=ast.parse(original);tree.body[0].name='frozen_step_without_verbose_audit'
    transform=AuditOnly();tree=transform.visit(tree);ast.fix_missing_locations(tree)
    assert len(transform.changed)==8,transform.changed
    prefix='''# Generated by sim.generate_fast; architectural statements remain from pinned core.
# Frozen source SHA256: '''+CORE_SHA256+'''
from .core import sh2e,SimulationStop
MASK32=sh2e.MASK32
sx=sh2e.sx
hx=sh2e.hx
div1_step=sh2e.div1_step
'''
    text=prefix+ast.unparse(tree)+'\n'
    target=Path(__file__).with_name('fast_step.py');target.write_text(text)
    print({'file':str(target),'sha256':sha256(text.encode()).hexdigest(),'transformations':transform.changed})

if __name__=='__main__':run()
